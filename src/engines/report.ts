import type { Report } from "@/lib/types";

/**
 * The unified report model — every tool produces one of these.
 * Renders to Markdown / JSON for export; the UI renders it natively.
 */
export function reportToMarkdown(r: Report): string {
  const lines: string[] = [];
  lines.push(`# ${r.title}`);
  lines.push("");
  lines.push(`**Tool:** ${r.toolLabel}  `);
  lines.push(`**Generated:** ${r.generatedAt}`);
  if (r.score !== undefined) {
    lines.push(`**Score:** ${r.score}/100`);
  }
  lines.push("");
  lines.push(r.summary);
  lines.push("");

  if (r.findings.length > 0) {
    lines.push("## Findings");
    lines.push("");
    for (const f of r.findings) {
      const loc = f.location ? ` (${f.location})` : "";
      lines.push(`- **[${f.severity.toUpperCase()}]** ${f.title}${loc}`);
      lines.push(`  ${f.detail}`);
    }
    lines.push("");
  }

  for (const s of r.sections) {
    lines.push(`## ${s.heading}`);
    lines.push("");
    if (s.body) lines.push(s.body);
    if (s.rows?.length) {
      lines.push("| | |");
      lines.push("|---|---|");
      for (const [k, v] of s.rows) lines.push(`| ${k} | ${v} |`);
    }
    if (s.code) {
      lines.push("```");
      lines.push(s.code);
      lines.push("```");
    }
    lines.push("");
  }

  if (r.meta && Object.keys(r.meta).length > 0) {
    lines.push("## Metadata");
    lines.push("");
    for (const [k, v] of Object.entries(r.meta)) {
      lines.push(`- **${k}:** ${v}`);
    }
  }

  lines.push("---");
  lines.push(
    "_Generated by ForgeKit — https://github.com/sujeeth777/ForgeKit_",
  );
  return lines.join("\n");
}

export function reportToJSON(r: Report): string {
  return JSON.stringify(r, null, 2);
}

export function reportFilename(r: Report, ext: string): string {
  const stamp = r.generatedAt.slice(0, 10);
  return `forgekit-${r.tool}-${stamp}.${ext}`;
}
